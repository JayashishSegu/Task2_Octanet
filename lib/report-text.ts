import type { RoastReport } from "./types";

/** Render a report as shareable Markdown (used by "Copy report"). */
export function reportToMarkdown(report: RoastReport): string {
  const lines: string[] = [
    `# 🔥 Website Roast — ${report.domain}`,
    "",
    `**URL:** ${report.finalUrl}`,
    `**Analyzed:** ${new Date(report.analyzedAt).toLocaleString()}`,
    `**Overall Score:** ${report.overallScore}/100 (${report.grade})`,
    "",
    `> ${report.tagline}`,
    "",
    "## Category Scores",
    "",
    "| Category | Score |",
    "|---|---|",
    ...report.categories.map((c) => `| ${c.name} | ${c.score}/100 |`),
    "",
    "## 🔥 The Roast",
    "",
    ...report.roasts.flatMap((r) => [`- ${r.line}`, `  - _Based on: ${r.basedOn}_`]),
    "",
    "## 🛠 Improvement Report",
    "",
    ...report.improvements.flatMap((i) => [
      `### [${i.priority}] ${i.issue}`,
      `- **Why it matters:** ${i.whyItMatters}`,
      `- **How to fix:** ${i.howToFix}`,
      `- **Expected impact:** ${i.expectedImpact}`,
      "",
    ]),
    "## 🏆 Wins",
    "",
    ...report.wins.map((w) => `- ${w}`),
    "",
    "## ⚖️ Final Verdict",
    "",
    report.verdict.summary,
    "",
    `- **Would you launch this?** ${report.verdict.wouldYouLaunchThis}`,
    `- **Would investors trust it?** ${report.verdict.wouldInvestorsTrustIt}`,
    `- **Would users stay?** ${report.verdict.wouldUsersStay}`,
    `- **Would Google love it?** ${report.verdict.wouldGoogleLoveIt}`,
    "",
    "---",
    "_Generated by Website Roast — brutally honest, evidence-based website reviews._",
  ];
  return lines.join("\n");
}
